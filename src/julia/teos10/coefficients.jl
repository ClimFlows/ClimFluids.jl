# coefficients of the derivative of the polynomial Σₖ cₖ xᵏ
TEOS_derivative(c::Tuple) = ntuple(k -> k * c[k+1], length(c) - 1)
TEOS_derivative(::Tuple{Any}) = (0.0,)

# a polynomial with the coefficients of its first and second derivatives
TEOS_with_derivatives(c) = (c, TEOS_derivative(c), TEOS_derivative(TEOS_derivative(c)))

